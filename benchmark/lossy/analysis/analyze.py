"""Analyze MSFragger search results across lossy compression schemes.

Compares peptide identifications from each lossy-compressed mzML against
the uncompressed original, producing a diverging bar chart and summary TSV.
"""

import os
import sys

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


# ---------------------------------------------------------------------------
# Publication style setup (matches mscompress-dl-training conventions)
# ---------------------------------------------------------------------------

def _setup_style():
    """Configure matplotlib for publication-quality output with serif fonts."""
    mpl.rcParams.update({
        # Font
        "font.family": "serif",
        "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
        "mathtext.fontset": "stix",
        "font.size": 14,
        "axes.labelsize": 15,
        "axes.titlesize": 16,
        "xtick.labelsize": 12,
        "ytick.labelsize": 12,
        "legend.fontsize": 12,
        # Lines / markers
        "lines.linewidth": 1.5,
        "lines.markersize": 6,
        # Axes
        "axes.linewidth": 0.8,
        "axes.spines.top": False,
        "axes.spines.right": False,
        # Ticks
        "xtick.major.width": 0.8,
        "ytick.major.width": 0.8,
        "xtick.direction": "out",
        "ytick.direction": "out",
        # Legend
        "legend.frameon": False,
        # Saving
        "savefig.dpi": 300,
        "savefig.bbox": "tight",
        "savefig.pad_inches": 0.05,
        "pdf.fonttype": 42,   # editable text in PDFs
        "ps.fonttype": 42,
    })

RESULTS_DIR = "/results"
PLOTS_DIR = os.path.join(RESULTS_DIR, "plots")
BASELINE_LABEL = "original"
PSM_FILENAME = "percolator-psms.txt"
SKIP_DIRS = {"plots"}
SCHEMES_FILE = os.path.join(RESULTS_DIR, "schemes.txt")


ALGO_DISPLAY = {
    "cast": "Cast",
    "cast16": "Cast16",
    "delta16": "Delta16",
    "delta24": "Delta24",
    "delta32": "Delta32",
    "bitpack": "Bitpack",
    "vbr": "VBR",
    "log": "Log",
}


def format_scheme_label(label: str) -> str:
    """Convert a scheme label like 'mz_cast_int_log' to 'm/z: Cast + Int: Log'."""
    if label == "lossless":
        return "Lossless"

    import re
    m = re.match(r"^mz_(\w+?)_int_(\w+)$", label)
    if m:
        mz_algo = ALGO_DISPLAY.get(m.group(1), m.group(1))
        int_algo = ALGO_DISPLAY.get(m.group(2), m.group(2))
        return f"m/z: {mz_algo}\nInt: {int_algo}"

    m = re.match(r"^mz_(\w+)$", label)
    if m:
        algo = ALGO_DISPLAY.get(m.group(1), m.group(1))
        return f"m/z: {algo}"

    m = re.match(r"^int_(\w+)$", label)
    if m:
        algo = ALGO_DISPLAY.get(m.group(1), m.group(1))
        return f"Int: {algo}"

    return label


def load_peptides(psm_tsv_path: str, qvalue_threshold: float = 0.01) -> set[str]:
    """Load unique peptide sequences from a Percolator PSM output file."""
    df = pd.read_csv(psm_tsv_path, sep="\t")
    df = df[df["q-value"] <= qvalue_threshold]
    # Percolator peptide format: flanking.SEQUENCE.flanking — extract the core sequence.
    peptides = df["peptide"].str.replace(r"^.*?\.(.*?)\..*$", r"\1", regex=True)
    return set(peptides.unique())


def get_file_size_mb(path: str) -> float | None:
    """Return file size in MB, or None if file doesn't exist."""
    if os.path.isfile(path):
        return os.path.getsize(path) / (1024 * 1024)
    return None


def discover_schemes() -> list[str]:
    """Find all scheme directories that have a psm.tsv.

    Uses the order from schemes.txt (generated by generate_schemes.sh)
    if available, otherwise falls back to alphabetical discovery.
    """
    # Build ordered list from schemes.txt if it exists
    ordered: list[str] = []
    if os.path.isfile(SCHEMES_FILE):
        with open(SCHEMES_FILE) as f:
            for line in f:
                label = line.strip().split(":")[0]
                if label:
                    ordered.append(label)

    schemes = []
    for name in os.listdir(RESULTS_DIR):
        if name in SKIP_DIRS or name == BASELINE_LABEL:
            continue
        psm_path = os.path.join(RESULTS_DIR, name, PSM_FILENAME)
        if os.path.isfile(psm_path):
            schemes.append(name)

    if ordered:
        # Preserve schemes.txt order; append any extras alphabetically
        order_map = {s: i for i, s in enumerate(ordered)}
        schemes.sort(key=lambda s: (order_map.get(s, len(ordered)), s))
    else:
        schemes.sort()

    return schemes


def main() -> None:
    os.makedirs(PLOTS_DIR, exist_ok=True)

    # Load baseline
    baseline_path = os.path.join(RESULTS_DIR, BASELINE_LABEL, PSM_FILENAME)
    if not os.path.isfile(baseline_path):
        print(f"ERROR: Baseline {baseline_path} not found.", file=sys.stderr)
        sys.exit(1)

    baseline_peptides = load_peptides(baseline_path)
    baseline_count = len(baseline_peptides)
    print(f"Baseline ({BASELINE_LABEL}): {baseline_count} unique peptides")

    # Get original mzML size for compression ratio
    original_mzml = os.path.join("/data", "reference.mzML")
    original_size = get_file_size_mb(original_mzml)

    # Analyze each scheme
    schemes = discover_schemes()
    if not schemes:
        print("ERROR: No scheme results found.", file=sys.stderr)
        sys.exit(1)

    rows = []
    for label in schemes:
        psm_path = os.path.join(RESULTS_DIR, label, PSM_FILENAME)
        peptides = load_peptides(psm_path)
        gained = peptides - baseline_peptides
        lost = baseline_peptides - peptides
        msz_path = os.path.join(RESULTS_DIR, label, "compressed.msz")
        msz_size = get_file_size_mb(msz_path)

        ratio = None
        if original_size and msz_size:
            ratio = msz_size / original_size

        rows.append(
            {
                "scheme": label,
                "total_peptides": len(peptides),
                "gained": len(gained),
                "lost": len(lost),
                "net_change": len(gained) - len(lost),
                "compressed_mb": round(msz_size, 2) if msz_size else None,
                "compression_ratio": round(ratio, 4) if ratio else None,
            }
        )
        print(
            f"  {label}: {len(peptides)} peptides "
            f"(+{len(gained)} / -{len(lost)})"
        )

    summary = pd.DataFrame(rows)

    # Save summary TSV
    summary_path = os.path.join(PLOTS_DIR, "summary.tsv")
    summary.to_csv(summary_path, sep="\t", index=False)
    print(f"\nSummary saved to {summary_path}")

    # ── Plot ────────────────────────────────────────────────────────────────
    _setup_style()

    # Convert to percentage relative to baseline
    gained_pct = summary["gained"].values / baseline_count * 100
    lost_pct = summary["lost"].values / baseline_count * 100
    scheme_labels = [format_scheme_label(s) for s in summary["scheme"].values]
    x = np.arange(len(summary))

    # Colors — Wong colorblind-safe palette
    color_gained = "#009E73"  # green
    color_lost = "#D55E00"    # vermilion
    color_ratio = "#0072B2"   # blue

    # Two subplots with different y-scales joined seamlessly at zero
    max_gained = max(gained_pct) if max(gained_pct) > 0 else 0.1
    max_lost = max(lost_pct) if max(lost_pct) > 0 else 0.1
    gained_pad = max_gained * 0.35
    lost_pad = max_lost * 0.15

    fig, (ax_top, ax_bot) = plt.subplots(
        2, 1,
        figsize=(max(8, len(summary) * 0.55), 5.5),
        sharex=True,
        gridspec_kw={"height_ratios": [1, 3], "hspace": 0},
    )

    bar_kw = dict(width=0.7, edgecolor="black", linewidth=0.6, zorder=3)

    # Draw bars on both axes
    for ax in (ax_top, ax_bot):
        ax.bar(x, gained_pct, color=color_gained, hatch="//", **bar_kw)
        ax.bar(x, [-v for v in lost_pct], color=color_lost, hatch="\\\\", **bar_kw)
        ax.yaxis.grid(True, linewidth=0.3, alpha=0.5)
        ax.xaxis.grid(True, linewidth=0.3, alpha=0.3)
        ax.set_axisbelow(True)

    # Top: gained region only (0 to max), bottom: lost region only (-max to 0)
    ax_top.set_ylim(0, max_gained + gained_pad)
    ax_top.yaxis.set_major_locator(mpl.ticker.MaxNLocator(nbins=4))
    ax_top.yaxis.set_major_formatter(mpl.ticker.FuncFormatter(lambda v, _: f"{v:g}%"))
    ax_top.spines["bottom"].set_visible(False)
    ax_top.tick_params(axis="x", which="both", bottom=False, labelbottom=False)

    ax_bot.set_ylim(-(max_lost + lost_pad), 0)
    ax_bot.yaxis.set_major_locator(mpl.ticker.MaxNLocator(nbins=5, symmetric=False))
    ax_bot.yaxis.set_major_formatter(mpl.ticker.FormatStrFormatter("%.0f%%"))
    ax_bot.spines["top"].set_visible(True)
    ax_bot.spines["top"].set_linewidth(0.8)

    # X-axis labels
    ax_bot.set_xticks(x)
    ax_bot.set_xticklabels(scheme_labels, rotation=90, ha="center", va="top")

    # Y-label centered between the two panels
    fig.text(0.02,
             (ax_top.get_position().y1 + ax_bot.get_position().y0) / 2,
             "Peptides Changed (%)", va="center", ha="center",
             rotation="vertical", fontsize=mpl.rcParams["axes.labelsize"])

    # Legend
    from matplotlib.patches import Patch
    legend_elements = [
        Patch(facecolor=color_gained, edgecolor="black", linewidth=0.6, hatch="//", label="Gained"),
        Patch(facecolor=color_lost, edgecolor="black", linewidth=0.6, hatch="\\\\", label="Lost"),
    ]
    ax_top.legend(handles=legend_elements, loc="upper left", ncol=2)

    fig.subplots_adjust(left=0.08, right=0.97, top=0.97, bottom=0.25, hspace=0)

    # Save as PDF + SVG (publication) and PNG (preview)
    for ext in ("pdf", "svg", "png"):
        fig.savefig(os.path.join(PLOTS_DIR, f"peptide_comparison.{ext}"))
    plt.close(fig)
    print(f"Plots saved to {PLOTS_DIR}/peptide_comparison.{{pdf,svg,png}}")

    # ── Compression ratio plot ─────────────────────────────────────────────
    ratio_df = summary.dropna(subset=["compression_ratio"]).copy()
    if not ratio_df.empty and original_size:
        fig, ax = plt.subplots(
            figsize=(max(8, len(ratio_df) * 0.55), 4),
        )

        rx = np.arange(len(ratio_df))
        ratios = ratio_df["compression_ratio"].values
        sizes = ratio_df["compressed_mb"].values
        rlabels = [format_scheme_label(s) for s in ratio_df["scheme"].values]

        bars = ax.bar(
            rx, ratios, width=0.7, color=color_ratio, hatch="xx",
            edgecolor="black", linewidth=0.6, zorder=3,
        )

        # Annotate each bar with the compression ratio
        for i, r in enumerate(ratios):
            ax.text(
                i, r + 0.005, f"{r:.2f}",
                ha="center", va="bottom", fontsize=10, color="#333",
            )

        ax.set_xticks(rx)
        ax.set_xticklabels(rlabels, rotation=90, ha="center", va="top")
        ax.set_ylabel("Compression Ratio")
        ax.set_ylim(bottom=0)
        ax.yaxis.set_major_locator(mpl.ticker.MaxNLocator(nbins=6))
        ax.yaxis.grid(True, linewidth=0.3, alpha=0.5)
        ax.xaxis.grid(True, linewidth=0.3, alpha=0.3)
        ax.set_axisbelow(True)

        fig.subplots_adjust(bottom=0.30)

        for ext in ("pdf", "svg", "png"):
            fig.savefig(os.path.join(PLOTS_DIR, f"compression_ratio.{ext}"))
        plt.close(fig)
        print(f"Plots saved to {PLOTS_DIR}/compression_ratio.{{pdf,svg,png}}")


    # ── Combined plot: compression ratio + peptide change ────────────────
    combo_df = summary.dropna(subset=["compression_ratio"]).copy()
    if not combo_df.empty and original_size:
        cx = np.arange(len(combo_df))
        c_ratios = combo_df["compression_ratio"].values
        c_gained_pct = combo_df["gained"].values / baseline_count * 100
        c_lost_pct = combo_df["lost"].values / baseline_count * 100
        c_labels = [format_scheme_label(s) for s in combo_df["scheme"].values]

        c_max_gained = max(c_gained_pct) if max(c_gained_pct) > 0 else 0.1
        c_max_lost = max(c_lost_pct) if max(c_lost_pct) > 0 else 0.1

        figw = max(8, len(combo_df) * 0.55)
        fig = plt.figure(figsize=(figw, 7))
        # Two gridspecs: one for the joined peptide panels, one for ratio
        gs_pep = fig.add_gridspec(2, 1, height_ratios=[1, 3],
                                  hspace=0, top=0.93, bottom=0.52,
                                  left=0.08, right=0.97)
        gs_rat = fig.add_gridspec(1, 1,
                                  top=0.47, bottom=0.22,
                                  left=0.08, right=0.97)
        ax_gain = fig.add_subplot(gs_pep[0])
        ax_loss = fig.add_subplot(gs_pep[1], sharex=ax_gain)
        ax_ratio = fig.add_subplot(gs_rat[0], sharex=ax_gain)

        bar_kw = dict(width=0.7, edgecolor="black", linewidth=0.6, zorder=3)

        # --- Top panel: gained peptides ---
        ax_gain.bar(cx, c_gained_pct, color=color_gained, hatch="//", **bar_kw)
        ax_gain.set_ylim(0, c_max_gained + c_max_gained * 0.35)
        ax_gain.yaxis.set_major_locator(mpl.ticker.MaxNLocator(nbins=3))
        ax_gain.yaxis.set_major_formatter(mpl.ticker.FuncFormatter(lambda v, _: f"{v:g}%"))
        ax_gain.yaxis.grid(True, linewidth=0.3, alpha=0.5)
        ax_gain.xaxis.grid(True, linewidth=0.3, alpha=0.3)
        ax_gain.set_axisbelow(True)
        ax_gain.spines["bottom"].set_visible(False)
        ax_gain.tick_params(axis="x", which="both", bottom=False)

        # --- Middle panel: lost peptides ---
        ax_loss.bar(cx, [-v for v in c_lost_pct], color=color_lost, hatch="\\\\", **bar_kw)
        ax_loss.set_ylim(-(c_max_lost + c_max_lost * 0.15), 0)
        ax_loss.yaxis.set_major_locator(mpl.ticker.MaxNLocator(nbins=5, symmetric=False))
        ax_loss.yaxis.set_major_formatter(mpl.ticker.FormatStrFormatter("%.0f%%"))
        ax_loss.yaxis.grid(True, linewidth=0.3, alpha=0.5)
        ax_loss.xaxis.grid(True, linewidth=0.3, alpha=0.3)
        ax_loss.set_axisbelow(True)
        ax_loss.spines["top"].set_visible(True)
        ax_loss.spines["top"].set_linewidth(0.8)
        ax_loss.spines["bottom"].set_visible(False)
        ax_loss.tick_params(axis="x", which="both", bottom=False, labelbottom=False)

        # Y-label centered between the gain and loss panels
        fig.text(0.02,
                 (ax_gain.get_position().y1 + ax_loss.get_position().y0) / 2,
                 "Peptides Changed (%)", va="center", ha="center",
                 rotation="vertical", fontsize=mpl.rcParams["axes.labelsize"])

        # Legend with all three series
        from matplotlib.patches import Patch
        legend_elements = [
            Patch(facecolor=color_gained, edgecolor="black", linewidth=0.6, hatch="//", label="Gained Peptides"),
            Patch(facecolor=color_lost, edgecolor="black", linewidth=0.6, hatch="\\\\", label="Lost Peptides"),
            Patch(facecolor=color_ratio, edgecolor="black", linewidth=0.6, hatch="xx", label="Compression Ratio"),
        ]
        fig.legend(handles=legend_elements, loc="upper center", ncol=3,
                   bbox_to_anchor=(0.5, 1.0))

        # --- Bottom panel: compression ratio ---
        ax_ratio.bar(cx, c_ratios, color=color_ratio, hatch="xx", **bar_kw)
        for i, r in enumerate(c_ratios):
            ax_ratio.text(
                i, r + 0.005, f"{r:.2f}",
                ha="center", va="bottom", fontsize=10, color="#333",
            )
        ax_ratio.set_ylabel("Compression Ratio")
        ax_ratio.yaxis.set_label_coords(-0.055, 0.5)
        ax_ratio.set_ylim(bottom=0)
        ax_ratio.yaxis.set_major_locator(mpl.ticker.MaxNLocator(nbins=5))
        ax_ratio.yaxis.grid(True, linewidth=0.3, alpha=0.5)
        ax_ratio.xaxis.grid(True, linewidth=0.3, alpha=0.3)
        ax_ratio.set_axisbelow(True)
        ax_ratio.spines["top"].set_visible(False)

        # X-axis labels on the bottom panel
        ax_ratio.set_xticks(cx)
        ax_ratio.set_xticklabels(c_labels, rotation=90, ha="center", va="top")


        for ext in ("pdf", "svg", "png"):
            fig.savefig(os.path.join(PLOTS_DIR, f"combined.{ext}"))
        plt.close(fig)
        print(f"Plots saved to {PLOTS_DIR}/combined.{{pdf,svg,png}}")


if __name__ == "__main__":
    main()

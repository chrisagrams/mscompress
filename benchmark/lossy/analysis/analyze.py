"""Analyze MSFragger search results across lossy compression schemes.

Compares peptide identifications from each lossy-compressed mzML against
the uncompressed original, producing a diverging bar chart and summary TSV.
"""

import os
import sys

import matplotlib.pyplot as plt
import pandas as pd

RESULTS_DIR = "/results"
PLOTS_DIR = os.path.join(RESULTS_DIR, "plots")
BASELINE_LABEL = "original"
PSM_FILENAME = "psm.tsv"
SKIP_DIRS = {"plots"}
SCHEMES_FILE = os.path.join(RESULTS_DIR, "schemes.txt")


def load_peptides(psm_tsv_path: str) -> set[str]:
    """Load unique peptide sequences from a Philosopher psm.tsv file."""
    df = pd.read_csv(psm_tsv_path, sep="\t")
    return set(df["Peptide"].unique())


def get_file_size_mb(path: str) -> float | None:
    """Return file size in MB, or None if file doesn't exist."""
    if os.path.isfile(path):
        return os.path.getsize(path) / (1024 * 1024)
    return None


def discover_schemes() -> list[str]:
    """Find all scheme directories that have a psm.tsv.

    Uses the order from schemes.txt (generated by generate_schemes.sh)
    if available, otherwise falls back to alphabetical discovery.
    """
    # Build ordered list from schemes.txt if it exists
    ordered: list[str] = []
    if os.path.isfile(SCHEMES_FILE):
        with open(SCHEMES_FILE) as f:
            for line in f:
                label = line.strip().split(":")[0]
                if label:
                    ordered.append(label)

    schemes = []
    for name in os.listdir(RESULTS_DIR):
        if name in SKIP_DIRS or name == BASELINE_LABEL:
            continue
        psm_path = os.path.join(RESULTS_DIR, name, PSM_FILENAME)
        if os.path.isfile(psm_path):
            schemes.append(name)

    if ordered:
        # Preserve schemes.txt order; append any extras alphabetically
        order_map = {s: i for i, s in enumerate(ordered)}
        schemes.sort(key=lambda s: (order_map.get(s, len(ordered)), s))
    else:
        schemes.sort()

    return schemes


def main() -> None:
    os.makedirs(PLOTS_DIR, exist_ok=True)

    # Load baseline
    baseline_path = os.path.join(RESULTS_DIR, BASELINE_LABEL, PSM_FILENAME)
    if not os.path.isfile(baseline_path):
        print(f"ERROR: Baseline {baseline_path} not found.", file=sys.stderr)
        sys.exit(1)

    baseline_peptides = load_peptides(baseline_path)
    baseline_count = len(baseline_peptides)
    print(f"Baseline ({BASELINE_LABEL}): {baseline_count} unique peptides")

    # Get original mzML size for compression ratio
    original_mzml = os.path.join("/data", "reference.mzML")
    original_size = get_file_size_mb(original_mzml)

    # Analyze each scheme
    schemes = discover_schemes()
    if not schemes:
        print("ERROR: No scheme results found.", file=sys.stderr)
        sys.exit(1)

    rows = []
    for label in schemes:
        psm_path = os.path.join(RESULTS_DIR, label, PSM_FILENAME)
        peptides = load_peptides(psm_path)
        gained = peptides - baseline_peptides
        lost = baseline_peptides - peptides
        msz_path = os.path.join(RESULTS_DIR, label, "compressed.msz")
        msz_size = get_file_size_mb(msz_path)

        ratio = None
        if original_size and msz_size:
            ratio = msz_size / original_size

        rows.append(
            {
                "scheme": label,
                "total_peptides": len(peptides),
                "gained": len(gained),
                "lost": len(lost),
                "net_change": len(gained) - len(lost),
                "compressed_mb": round(msz_size, 2) if msz_size else None,
                "compression_ratio": round(ratio, 4) if ratio else None,
            }
        )
        print(
            f"  {label}: {len(peptides)} peptides "
            f"(+{len(gained)} / -{len(lost)})"
        )

    summary = pd.DataFrame(rows)

    # Save summary TSV
    summary_path = os.path.join(PLOTS_DIR, "summary.tsv")
    summary.to_csv(summary_path, sep="\t", index=False)
    print(f"\nSummary saved to {summary_path}")

    # ── Plot ────────────────────────────────────────────────────────────────
    fig, ax = plt.subplots(figsize=(12, 6))

    x = range(len(summary))
    labels = summary["scheme"]
    gained = summary["gained"]
    lost = summary["lost"]

    ax.bar(x, gained, color="#2ecc71", label="Gained peptides", zorder=3)
    ax.bar(x, [-v for v in lost], color="#e74c3c", label="Lost peptides", zorder=3)

    # Annotate total count on top of each bar group
    for i, row in summary.iterrows():
        y_top = max(row["gained"], row["lost"]) + baseline_count * 0.01
        ax.text(
            i,
            y_top,
            str(row["total_peptides"]),
            ha="center",
            va="bottom",
            fontsize=7,
            color="#555",
        )

    ax.set_xticks(list(x))
    ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=8)
    ax.set_ylabel("Peptide count")
    ax.set_title(
        f"Impact of lossy compression on peptide identification\n"
        f"(baseline: {baseline_count} peptides from uncompressed mzML)"
    )
    ax.axhline(0, color="black", linewidth=0.8)
    ax.legend(loc="upper right")
    ax.grid(axis="y", alpha=0.3, zorder=0)

    plt.tight_layout()
    plot_path = os.path.join(PLOTS_DIR, "peptide_comparison.png")
    fig.savefig(plot_path, dpi=150)
    print(f"Plot saved to {plot_path}")


if __name__ == "__main__":
    main()

"""Per-spectrum index of batch .mszx archives: writing it, reading it, and
querying it.

Expected values come from the golden fixtures in test/data/mszx, generated by
the C CLI, so these tests also check the Python reader against the C reader.
"""

from __future__ import annotations

import csv
import json
import math
import shutil
import tarfile
from pathlib import Path

import numpy as np
import pytest

from mscompress import MSZXBatchFile, MSZXBatchWriter, QueryResult, SpectrumIndex
from mscompress.mszx import compress_batch

REPO_ROOT = Path(__file__).resolve().parents[2]
DATA = REPO_ROOT / "test" / "data"
GOLDEN_TSV = DATA / "mszx" / "index_golden.tsv"
GOLDEN_JSON = DATA / "mszx" / "index_golden.json"


def _build(tmp_path: Path, index: bool = True) -> Path:
    """The archive the golden fixtures describe: a.mzML then b.mzML."""
    golden = json.loads(GOLDEN_JSON.read_text())
    src = tmp_path / "in"
    src.mkdir(exist_ok=True)
    for name, data_file in golden["inputs"]:
        shutil.copy(DATA / data_file, src / name)
    out = tmp_path / ("idx.mszx" if index else "noidx.mszx")
    compress_batch(src, out, index=index)
    return out


@pytest.fixture(scope="module")
def indexed(tmp_path_factory) -> Path:
    return _build(tmp_path_factory.mktemp("index"))


@pytest.fixture(scope="module")
def unindexed(tmp_path_factory) -> Path:
    return _build(tmp_path_factory.mktemp("noindex"), index=False)


def _golden_rows():
    with GOLDEN_TSV.open() as f:
        return list(csv.DictReader(f, delimiter="\t"))


# -- writing -----------------------------------------------------------------


def test_index_member_and_manifest_block(indexed):
    with tarfile.open(indexed) as tar:
        names = tar.getnames()
    assert names[-2:] == ["index.mszxi", "manifest.json"]

    with MSZXBatchFile.open(indexed) as archive:
        assert archive.manifest.version == "2.0"
        assert archive.has_index
        info = archive.manifest.index
        assert info.entry == "index.mszxi"
        assert info.format_version == 1
        assert info.sorted_by == ["rt_sec", "precursor_mz"]
        assert info.columns[:2] == ["entry", "spectrum_idx"]
        assert archive.manifest.to_dict()["index"] == info.to_dict()


def test_index_false_writes_no_index(unindexed):
    with tarfile.open(unindexed) as tar:
        assert "index.mszxi" not in tar.getnames()
    with MSZXBatchFile.open(unindexed) as archive:
        assert archive.manifest.version == "2.0"
        assert not archive.has_index
        assert archive.manifest.index is None


def test_writer_index_kwarg(tmp_path):
    out = tmp_path / "w.mszx"
    with MSZXBatchWriter(out, index=False) as w:
        w.add(DATA / "test.mzML")
        w.finish()
    with tarfile.open(out) as tar:
        assert "index.mszxi" not in tar.getnames()


# -- reading -----------------------------------------------------------------


def test_full_table_matches_golden(indexed):
    golden = _golden_rows()
    with MSZXBatchFile.open(indexed) as archive:
        index = archive.index
        assert isinstance(index, SpectrumIndex)
        assert len(index) == len(golden) == 150
        assert index.n_entries == 2

        frame = archive.query().to_frame()
        assert list(frame.columns) == list(golden[0].keys())
        for row, want in zip(frame.itertuples(index=False), golden):
            got = row._asdict()
            assert got["entry_name"] == want["entry_name"]
            for col in ("entry", "spectrum_idx", "scan"):
                assert got[col] == int(want[col])
            for col in ("ms_level", "charge"):  # 0 is printed as NA
                assert got[col] == (0 if want[col] == "NA" else int(want[col]))
            for col in ("rt_sec", "tic", "precursor_mz", "base_peak_mz"):
                if want[col] == "NA":
                    assert math.isnan(got[col])
                else:
                    assert got[col] == pytest.approx(float(want[col]), rel=1e-6)


@pytest.mark.parametrize(
    "case", json.loads(GOLDEN_JSON.read_text())["queries"], ids=lambda c: c["query"]
)
def test_queries_match_golden(indexed, case):
    terms = {k: tuple(v) for k, v in case["filter"].items()}
    with MSZXBatchFile.open(indexed) as archive:
        result = archive.query(**terms)
        hits = result.to_numpy()[["entry", "spectrum_idx"]].tolist()
    assert [list(h) for h in hits] == case["hits"]


def test_query_values_and_entry_names(indexed):
    with MSZXBatchFile.open(indexed) as archive:
        # Scalar = equality; None = open side.
        ms2 = archive.query(ms_level=2)
        assert len(ms2) == len(archive.query(ms_level=(2, 2)))
        assert len(archive.query(rt_sec=(None, None))) == 150
        assert len(archive.query(rt_sec=None)) == 150  # not filtered

        assert np.array_equal(
            archive.query(entry="b.msz").rows, archive.query(entry=1).rows
        )
        with pytest.raises(KeyError):
            archive.query(entry="missing.msz")
        with pytest.raises(TypeError):
            archive.query(rt=(5, 8))  # no aliases: columns are keywords


def test_missing_values_never_match(indexed):
    with MSZXBatchFile.open(indexed) as archive:
        # MS1 spectra have no precursor, so an unbounded precursor range
        # excludes every one of them.
        hits = archive.query(precursor_mz=(None, None)).to_numpy()
        assert len(hits) and (hits["ms_level"] == 2).all()
        assert not np.isnan(hits["precursor_mz"]).any()


def test_spectra_follow_rows(indexed):
    with MSZXBatchFile.open(indexed) as archive:
        result = archive.query(rt_sec=(5, 8))
        assert isinstance(result, QueryResult)
        table = result.to_numpy()
        spectra = list(result.spectra())
        assert len(spectra) == len(table)
        for spectrum, row in zip(spectra, table):
            assert spectrum.scan == row["scan"]
            assert spectrum.ms_level == row["ms_level"]
            assert spectrum.retention_time == pytest.approx(row["rt_sec"], rel=1e-5)


def test_query_without_index_raises(unindexed):
    with MSZXBatchFile.open(unindexed) as archive:
        with pytest.raises(ValueError, match="no spectrum index"):
            archive.query(rt_sec=(0, 10))
        with pytest.raises(ValueError, match="no spectrum index"):
            archive.index


def test_index_rejects_garbage():
    with pytest.raises(ValueError):
        SpectrumIndex(b"nope" * 16)


def test_index_rejects_truncation(indexed):
    with tarfile.open(indexed) as tar:
        data = tar.extractfile("index.mszxi").read()
    SpectrumIndex(data)
    # Cut inside the header, the entry offsets and the column directory:
    # a ValueError, never struct.error.
    for cut in (16, 40, 72):
        with pytest.raises(ValueError, match="truncated"):
            SpectrumIndex(data[:cut])
    # The sorted-key directory runs past the end (n_keys at byte 24).
    bad = bytearray(data)
    bad[24:28] = (1 << 20).to_bytes(4, "little")
    with pytest.raises(ValueError, match="truncated"):
        SpectrumIndex(bytes(bad))
